#!/usr/bin/env python3
"""Average weighted ORCA TDDFT/TDA orbital density differences over MD frames.

Requires Python 3.5+ and ORCA 6 orca_plot; Python standard library only.
No pip packages are needed. All molecular orbital grids are generated by orca_plot.
Python performs only cube bookkeeping, weighted sums, rigid fitting, and averaging.
Run: python3 average_edd.py orca_jobs --grid 80 --min-weight 0.01
     python3 average_edd.py orca_jobs --roots 1 2 --no-cleanup

Supply --spectra-dir DIRECTORY containing the state spectra from 5_average.py:
binned_averaged_spectrum_state_1.dat, binned_averaged_spectrum_state_2.dat, etc.
Default directory is the current working directory. --spectrum-template changes
the filename pattern; it must contain {state} or {root}. Input columns must be
Bin_Start Bin_End Bin_Center Transitions fosc, with wavelengths in nm.
Only non-zero fosc bins are eligible. For a frame/root outside those bins, do
not export its orbitals; its EDD is zero and the valid-frame denominator stays
unchanged. Inside an eligible bin, retain the original --min-weight cutoff.
Use the ORCA absorption-table wavelength where available (the same rounded
wavelength used by the spectrum script); otherwise convert the root excitation
energy. All MO contributions to one root share that excitation wavelength.
Bins are [start,end), except the final spectrum boundary, which is inclusive.

One immediate subdirectory per frame. Job basenames are automatically detected
separately in each directory and may differ between frames. Matching .out/.gbw
stems are preferred. If there is exactly one .out and one .gbw, they are paired
even if the output was renamed. Use --basename only as an optional override.
Only ORCA's printed
STATE N: E= ... transition tables are supported (not NTO tables or CC amplitudes).
A GBW alone does not contain the printed root transition weights.

Frame EDD = sum w_ia * (phi_a**2 - phi_i**2), using the printed weight after ':'.
Weights are NOT squared again or renormalized after thresholding. This requested
MO-pair map is a diagonal, unrelaxed approximation: it omits orbital coherence
cross terms and is not a full TDDFT excited-minus-ground state density. Real MOs
and spin-conserving alpha/beta transitions are supported. SOC/spinor and spin-flip
are not supported; multiple same-numbered roots/manifolds in one output are rejected.

Frames are rigidly fitted to the first usable geometry, then scalar DENSITIES
(not orbitals) are trilinearly interpolated to a common grid covering the union
of rotated native cube domains. Atoms must have the same order in every frame;
unwrap/reassemble PBC-split molecules before the VEE calculations. Default fit
uses non-hydrogen atoms (falls back to all atoms for fewer than three). Root
indices are averaged, without tracking electronic character at root crossings.
Roots are detected from the printed output tables. Directories with temporary
files or without normal ORCA termination are excluded. Temporary-name patterns
include *.tmp, *.tmp.*, *.temp, *.temp.*, *.lock, *.lck, *.part, and *.partial;
--temp-pattern adds extra globs if needed. .cis/.densities/.ges are not temporary.
Every valid output must
contain all selected roots, and every average uses the SAME denominator: the
number of valid outputs scanned. If construction fails, averaging stops rather
than silently changing that denominator. A present root with
no pairs passing the threshold contributes a zero map. Output:
root_N.average.EDD.cube, summary.csv, run.json. Cubes are in bohr and electron/bohr^3, positive
for accumulation and negative for depletion; final cube atoms are the reference
geometry. --grid sets ORCA's grid setting AND points per output axis (default 80).
The isolated plotting directory retains each GBW's original basename and copies
its companion density metadata, density containers, and CIS files. ORCA may
read these even when only molecular orbitals are requested.
Default cleanup removes only this run's copied job files, orbital cubes, and per-frame
EDDs after averages are saved; originals are never changed. --no-cleanup keeps
these under output/aux_RUN/. Failed runs retain auxiliaries for diagnosis.

Printed transition tables may already omit small contributions. Reducing
--min-weight cannot recover transitions omitted by the ORCA print threshold.
Inspect retained_weight and density integrals in summary.csv; use higher --grid
for convergence checks. Resampling is not exactly integral-conserving. Pure-Python voxel processing may
be slower than numerical libraries. Identical aligned grids skip interpolation.

orca_plot density algebra operates on ORCA density containers; it does not
provide the cross-frame alignment/resampling used here. Direct CIS/TDDFT
difference-density plots would also change the specified thresholded MO-pair
formula. This script therefore uses orca_plot for every retained orbital and
standard-library array/math for the required weighted EDD and frame averaging.
Reference: https://www.faccts.de/docs/orca/6.0/manual/contents/detailed/utilities.html
"""

