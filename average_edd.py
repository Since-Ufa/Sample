def temporary_entries(folder, extra_patterns):
    """Check file/directory names recursively; do not follow symlink directories."""
    patterns = TEMP_PATTERNS + (extra_patterns or [])
    found = []
    for base, directories, files in os.walk(str(folder), followlinks=False):
        for name in directories + files:
            if any(
                fnmatch.fnmatch(name.lower(), pattern.lower()) for pattern in patterns
            ):
                found.append(str(Path(base) / name))
    return sorted(found)


def discover(args):
    jobs, skipped = [], []
    folders = sorted(
        (
            p
            for p in args.base_dir.iterdir()
            if p.is_dir() and p.resolve() != args.output_dir.resolve()
        ),
        key=lambda p: [
            (1, int(x)) if x.isdigit() else (0, x) for x in re.split(r"(\d+)", p.name)
        ],
    )
    for folder in folders:
        temporary = temporary_entries(folder, args.temp_pattern)
        if temporary:
            skipped.append(
                {
                    "frame": folder.name,
                    "reason": "Temporary files/directories present",
                    "temporary_entries": temporary,
                }
            )
            print(
                f"SKIP {folder.name}: temporary files/directories present", flush=True
            )
            continue
        files = [p for p in folder.iterdir() if p.is_file()]
        outputs = sorted(p for p in files if p.suffix.lower() == ".out")
        wavefunctions = sorted(p for p in files if p.suffix.lower() == ".gbw")
        usable, reasons = [], []
        for output in outputs:
            matches = [p for p in wavefunctions if p.stem == output.stem]
            if args.basename:
                # The optional override identifies the GBW, not the output name.
                matches = [p for p in wavefunctions if p.stem == args.basename]
            elif not matches and len(wavefunctions) == 1:
                matches = wavefunctions
            if len(matches) != 1:
                reasons.append(f"{output.name}: cannot uniquely identify GBW")
                continue
            text = output.read_text(errors="replace")
            if "ORCA TERMINATED NORMALLY" not in text:
                reasons.append(f"{output.name}: missing ORCA TERMINATED NORMALLY")
                continue
            try:
                states = parse_states(output)
                usable.append((output, matches[0], states))
            except ValueError as exc:
                reasons.append(str(exc))
        if len(usable) > 1:
            raise ValueError(
                f"{folder}: multiple usable VEE outputs; retain one output per frame"
            )
        if usable:
            jobs.append(usable[0])
            print(
                f"Detected {folder.name}: {usable[0][0].name} + {usable[0][1].name}; {len(usable[0][2])} roots",
                flush=True,
            )
        else:
            skipped.append(
                {
                    "frame": folder.name,
                    "reason": "; ".join(reasons) or "No usable .out/.gbw pair",
                }
            )
            print("SKIP {}: {}".format(folder.name, skipped[-1]["reason"]), flush=True)
    return jobs, skipped


def save_summary(args, records):
    columns = [
        "frame",
        "root",
        "status",
        "pairs",
        "printed_weight",
        "retained_weight",
        "wavelength_nm",
        "spectral_selected",
        "bin_start_nm",
        "bin_end_nm",
        "rmsd_angstrom",
        "native_integral",
        "common_integral",
        "message",
    ]
    with (args.output_dir / "summary.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        writer.writerows(records)


def run(args):
    args.output_dir.mkdir(parents=True, exist_ok=True)
    jobs, skipped = discover(args)
    if not jobs:
        (args.output_dir / "run.json").write_text(
            json.dumps(
                {"valid_outputs_scanned": 0, "skipped_inputs": skipped}, indent=2
            )
            + "\n"
        )
        raise ValueError("No valid completed frame outputs found; see run.json")
    detected_roots = sorted({root for _, _, states in jobs for root in states})
    roots = args.roots or detected_roots
    complete_jobs = []
    for output, gbw, states in jobs:
        missing = sorted(set(roots) - set(states))
        empty_tables = sorted(
            root for root in roots if root in states and not states[root]
        )
        if missing or empty_tables:
            reason = f"Missing roots {missing}; empty transition tables {empty_tables}"
            skipped.append({"frame": output.parent.name, "reason": reason})
            print(f"SKIP {output.parent.name}: {reason}", flush=True)
        else:
            complete_jobs.append((output, gbw, states))
    jobs = complete_jobs
    divisor = len(jobs)
    if not divisor:
        (args.output_dir / "run.json").write_text(
            json.dumps(
                {"valid_outputs_scanned": 0, "roots": roots, "skipped_inputs": skipped},
                indent=2,
            )
            + "\n"
        )
        raise ValueError(
            "No outputs contain all selected roots with transition tables; see run.json"
        )
    print(
        f"Detected roots: {roots}; valid outputs scanned / averaging denominator: {divisor}",
        flush=True,
    )
    masks = load_spectrum_masks(args, roots)
    frame_wavelengths = {
        output: root_wavelengths(output, roots) for output, _, _ in jobs
    }
    if args.nroots is not None:
        print(
            "NOTE: --nroots is ignored; roots are detected from output files.",
            flush=True,
        )
    # Each run owns a unique directory; cleanup never globs source directories.
    work = Path(tempfile.mkdtemp(prefix="aux_", dir=str(args.output_dir)))
    records, frames, bounds, reference = [], [], [], None
    errors = []
    print(f"{len(jobs)} frames; roots {roots}; auxiliaries: {work}", flush=True)
    for frame_index, (output, gbw, states) in enumerate(jobs):
        folder = work / f"{frame_index:06d}_{output.parent.name}"
        folder.mkdir()
        wavelengths = frame_wavelengths[output]
        selected_bins = {
            root: masks[root].selected_bin(wavelengths[root]) for root in roots
        }
        selected = {
            root: [pair for pair in states[root] if pair[4] >= args.min_weight]
            if selected_bins[root] is not None
            else []
            for root in roots
        }
        orbitals = {
            (index, spin)
            for pairs in selected.values()
            for h, hs, e, es, _ in pairs
            for index, spin in [(h, hs), (e, es)]
        }
        try:
            paths = export_orbitals(gbw, orbitals, args, folder) if orbitals else {}
            template = (
                read_cube(next(iter(paths.values())))
                if paths
                else zero_template(output, args.grid)
            )
            if reference is None:
                reference = [row[:] for row in template.atoms]
            rotation, translation, rmsd = fitting(
                template.atoms, reference, args.alignment
            )
            frame_entries = []
            for root in roots:
                record = {
                    "frame": output.parent.name,
                    "root": root,
                    "status": "missing",
                    "pairs": 0,
                    "printed_weight": "",
                    "retained_weight": "",
                    "wavelength_nm": wavelengths[root],
                    "spectral_selected": selected_bins[root] is not None,
                    "bin_start_nm": selected_bins[root][0]
                    if selected_bins[root]
                    else "",
                    "bin_end_nm": selected_bins[root][1] if selected_bins[root] else "",
                    "rmsd_angstrom": rmsd,
                    "native_integral": "",
                    "common_integral": "",
                    "message": "",
                }
                if selected_bins[root] is None:
                    record["message"] = (
                        "Zero EDD: wavelength outside non-zero spectrum bins"
                    )
                elif not selected[root]:
                    record["message"] = "Zero EDD: no MO pairs pass min-weight"
                records.append(record)
                if root not in selected:
                    continue
                try:
                    density = weighted_density(template, paths, selected[root])
                    cube = Cube(
                        template.origin,
                        template.axes,
                        template.atoms,
                        density,
                        template.shape,
                    )
                    destination = folder / f"root_{root}.EDD.cube"
                    write_cube(
                        destination,
                        cube,
                        f"Frame {output.parent.name}; root {root}; native grid; e/bohr^3",
                    )
                    record.update(
                        status="ok",
                        pairs=len(selected[root]),
                        printed_weight=sum(p[4] for p in states[root]),
                        retained_weight=sum(p[4] for p in selected[root]),
                        native_integral=sum(density) * cube.volume,
                    )
                    frame_entries.append((root, destination, record))
                    print(
                        "{} root {}: {:.6f} nm, spectral_selected={}, {} pairs, weight={:.6f}".format(
                            output.parent.name,
                            root,
                            wavelengths[root],
                            record["spectral_selected"],
                            record["pairs"],
                            record["retained_weight"],
                        ),
                        flush=True,
                    )
                except Exception as exc:
                    record.update(status="failed", message=str(exc))
                    errors.append(f"{output.parent.name} root {root}: {exc}")
            if frame_entries:
                bounds.extend(
                    transform(point, rotation, translation)
                    for point in corners(template)
                )
                frames.append((rotation, translation, frame_entries))
        except Exception as exc:
            errors.append(f"{output.parent.name}: {exc}")
            print(f"ERROR: {errors[-1]}", flush=True)
            for root in roots:
                records.append(
                    {
                        "frame": output.parent.name,
                        "root": root,
                        "status": "failed",
                        "message": str(exc),
                    }
                )
    if errors or len(frames) != divisor:
        save_summary(args, records)
        failure = {
            "valid_outputs_scanned": divisor,
            "averaging_denominator": divisor,
            "roots": roots,
            "skipped_inputs": skipped,
            "errors": errors,
            "status": "failed: no new averaged cubes written",
            "auxiliaries": str(work),
        }
        (args.output_dir / "run.json").write_text(json.dumps(failure, indent=2) + "\n")
        raise RuntimeError(
            "Construction failed for valid inputs; no new averaged cubes written. "
            f"Denominator remains {divisor}. See run.json; auxiliaries retained at {work}"
        )
    lo = [min(point[j] for point in bounds) for j in range(3)]
    hi = [max(point[j] for point in bounds) for j in range(3)]
    axes = diagonal([(hi[j] - lo[j]) / (args.grid - 1) for j in range(3)])
    target = Cube(lo, axes, reference, zeros(args.grid**3), (args.grid,) * 3)
    counts = {}
    for root in roots:
        total, count = zeros(len(target.data)), 0
        for rotation, translation, entries in frames:
            for state, path, record in entries:
                if state != root:
                    continue
                sampled = resample(read_cube(path), rotation, translation, target)
                record["common_integral"] = sum(sampled) * target.volume
                for i, value in enumerate(sampled):
                    total[i] += value
                count += 1
        counts[root] = count
        if count != divisor:
            raise RuntimeError(
                f"Root {root} has {count} frame maps, expected the scanned denominator {divisor}"
            )
        if count:
            target.data = array("d", (value / divisor for value in total))
            destination = args.output_dir / f"root_{root}.average.EDD.cube"
            write_cube(
                destination,
                target,
                f"Root {root}; divisor={divisor} valid outputs; e/bohr^3; reference atoms",
            )
            print(f"SAVED {destination} ({count} frames)", flush=True)
        else:
            errors.append(
                f"Root {root}: no successful frames; no averaged cube written"
            )
    save_summary(args, records)
    report = {
        "configuration": {
            k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()
        },
        "roots": roots,
        "successful_frames_per_root": counts,
        "skipped_inputs": skipped,
        "detected_roots": detected_roots,
        "valid_outputs_scanned": divisor,
        "averaging_denominator": divisor,
        "spectral_filter": {
            "definition": "Root excitation wavelength must lie in a non-zero fosc bin of that root's averaged spectrum",
            "normalization": "Filtered frame/root maps are zero; denominator includes all valid frames",
            "sources": {
                root: {
                    "file": str(masks[root].path),
                    "nonzero_bins_nm": [
                        [lo, hi]
                        for lo, hi, intensity in masks[root].bins
                        if intensity != 0.0
                    ],
                }
                for root in roots
            },
            "selected_frames_per_root": {
                root: sum(
                    record.get("spectral_selected", False)
                    for record in records
                    if record["root"] == root and record["status"] == "ok"
                )
                for root in roots
            },
        },
        "detected_jobs": [
            {"frame": out.parent.name, "output": str(out), "gbw": str(gbw)}
            for out, gbw, _ in jobs
        ],
        "errors": errors,
        "reference_frame": next(r["frame"] for r in records if r["status"] == "ok"),
        "common_grid": {
            "shape": list(target.shape),
            "origin_bohr": lo,
            "axes_bohr": target.axes,
        },
        "definition": "sum printed_weight * (virtual_MO_squared - occupied_MO_squared); diagonal approximation",
        "auxiliaries": str(work),
    }
    (args.output_dir / "run.json").write_text(json.dumps(report, indent=2) + "\n")
    if args.cleanup and not errors:
        shutil.rmtree(str(work))
        print("Auxiliary orbital cubes and frame EDDs removed.", flush=True)
    elif errors:
        print(
            f"{len(errors)} errors; see run.json. Auxiliaries retained at {work}",
            file=sys.stderr,
        )
    return 1 if errors else 0


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "base_dir",
        type=Path,
        help="Directory containing immediate frame subdirectories",
    )
    parser.add_argument("--orca-plot", default="/opt/orca6/orca_plot")
    parser.add_argument("--grid", type=int, default=80)
    parser.add_argument("--min-weight", type=float, default=0.01)
    cleanup = parser.add_mutually_exclusive_group()
    cleanup.add_argument(
        "--cleanup",
        dest="cleanup",
        action="store_true",
        help="Remove auxiliary files after success (default: enabled)",
    )
    cleanup.add_argument(
        "--no-cleanup",
        dest="cleanup",
        action="store_false",
        help="Keep auxiliary files",
    )
    parser.set_defaults(cleanup=True)
    parser.add_argument(
        "--temp-pattern",
        action="append",
        default=[],
        help='Additional filename glob causing exclusion, e.g. --temp-pattern "*.scratch"',
    )
    parser.add_argument(
        "--roots",
        type=int,
        nargs="+",
        help="Selected roots; default: all detected roots",
    )
    parser.add_argument(
        "--nroots",
        type=int,
        help="Deprecated compatibility argument; ignored (roots detected automatically)",
    )
    parser.add_argument(
        "--basename",
        help="Optional common job-stem override; default: automatically detect each frame",
    )
    parser.add_argument("--output-dir", type=Path, default=Path("averaged_edd"))
    parser.add_argument(
        "--spectra-dir",
        type=Path,
        default=Path("."),
        help="Directory of per-state averaged-spectrum .dat files (default: current directory)",
    )
    parser.add_argument(
        "--spectrum-template",
        default="binned_averaged_spectrum_state_{state}.dat",
        help="Per-state spectrum filename pattern using {state} or {root}",
    )
    parser.add_argument(
        "--alignment", choices=["heavy", "all", "none"], default="heavy"
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=1800,
        help="Seconds allowed per frame orca_plot process",
    )
    args = parser.parse_args()
    if not args.base_dir.is_dir():
        parser.error("base_dir must be an existing directory")
    if (
        args.grid < 2
        or not math.isfinite(args.min_weight)
        or args.min_weight < 0
        or not math.isfinite(args.timeout)
        or args.timeout <= 0
    ):
        parser.error("Require grid >= 2, min-weight >= 0, and timeout > 0")
    if (
        args.nroots is not None
        and args.nroots < 1
        or args.roots
        and any(s < 1 for s in args.roots)
    ):
        parser.error("Root indices and nroots must be positive")
    if args.basename and (
        Path(args.basename).name != args.basename or args.basename in (".", "..")
    ):
        parser.error("basename must be a filename stem, without directories")
    if args.roots:
        args.roots = sorted(set(args.roots))
    args.base_dir = args.base_dir.resolve()
    args.output_dir = Path(os.path.abspath(str(args.output_dir)))
    args.spectra_dir = Path(os.path.abspath(str(args.spectra_dir)))
    if not args.spectra_dir.is_dir():
        parser.error("spectra-dir must be an existing directory")
    if not re.search(r"\{(?:state|root)(?::[^}]+)?\}", args.spectrum_template):
        parser.error("spectrum-template must contain {state} or {root}")
    if args.base_dir == args.output_dir:
        parser.error("output-dir must differ from base-dir")
    executable = shutil.which(args.orca_plot)
    if not executable:
        parser.error(f"orca_plot executable not found: {args.orca_plot}")
    args.orca_plot = str(Path(executable).resolve())
    try:
        return run(args)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
